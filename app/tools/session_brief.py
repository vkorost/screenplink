"""What every session, and every compaction, must start with.

Asked for directly on 2026-10-16, after I made a morning's worth of changes
without re-reading the rules:

    "We agree that we put down the rules that you will read after every
     compaction without fail so that we avoid all those issues that happened
     in the last couple of days (when you just fix one thing and break three
     other things)."

The agreement was already in CLAUDE.md -- "READ RULES.md FIRST, END TO END,
BEFORE WRITING ANY CODE" -- and it did not survive a compaction, because it
was a sentence addressed to someone whose memory had just been cleared.

So it stops being a thing to remember. This runs as a SessionStart hook and
prints, into the first thing the session sees:

  1. the state, READ FROM DISK by tools/status.py -- the gate score, the
     last GATE line with its role tag, the tags, his files, what is running.
     Three claims on this project were wrong because they were remembered
     rather than re-read, and status.py prints all three correctly.
  2. RULES.md in full. Not a summary and not the headings: the headings are
     what I thought I remembered this morning, and the rule I broke
     (A11: identify the camera by what it DOES) reads obvious as a heading
     and is only convincing with its incident attached.

Nothing here is generated by hand, so nothing here can quietly go stale.
"""

from __future__ import annotations

import io
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    # The console here is cp1252 and RULES.md contains arrows and dashes.
    # Without this the rules print 5KB in and die on an encode error, which
    # is a check that half-runs -- the exact shape of RULES C1. Replace
    # rather than fail: a rule rendered with a "?" in it is still the rule.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                    # noqa: BLE001
            pass
    py = ROOT / ".venv" / "Scripts" / "python.exe"
    try:
        r = subprocess.run([str(py), str(ROOT / "tools" / "status.py")],
                           capture_output=True, text=True, cwd=str(ROOT),
                           timeout=40)
        sys.stdout.write(r.stdout)
    except Exception as exc:                                 # noqa: BLE001
        print(f"(status.py did not run: {exc!r})")

    rules = ROOT / "RULES.md"
    print()
    print("=" * 68)
    print("THE RULES. Every one was learned by breaking it on this project.")
    print("Read them before changing any code -- including now, mid-session,")
    print("if this is a compaction. The failure they exist to stop is not")
    print("ignorance of a rule: it is fixing the instance in front of you and")
    print("leaving the same mistake standing in four other places.")
    print("=" * 68)
    print()
    try:
        sys.stdout.write(io.open(rules, encoding="utf-8").read())
    except Exception as exc:                                 # noqa: BLE001
        print(f"COULD NOT READ RULES.md ({exc!r}) -- read it by hand, now.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
