"""Where this project actually stands, in under forty lines, generated.

WHY THIS EXISTS
---------------
What gets carried between sessions today is `RULES.md` (579 lines) and
`CLAUDE.md` (~2900 lines), both written by hand, and both re-read by an
assistant whose context has just been compacted. That does not work, and
there is direct evidence: rewriting RULES.md I dropped six rules that were
in my own first draft, three of them describing damage done that same day.

Fable's recommendation, reviewing this codebase on 2026-10-15: the artifact
that survives compaction is the one that is SMALL, STRUCTURED, and
REGENERATED BY A SCRIPT rather than written by hand. Prose cannot be kept
honest; this can, because it reads the logs, the git tags and the files.

    .venv\\Scripts\\python.exe tools\\status.py

Prints only facts with a source. Every number comes from a GATE line, a
file, or git -- never from a memory of what was true. The three claims this
project has got wrong by remembering instead of reading were "17 seconds to
READY" (a harness log), "the arcade modes are hiding your holes"
(invented), and "ready" (from one good run).
"""

from __future__ import annotations

import io
import os
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The files that are HIS. Nothing may write them; three tests have.
OWNED = ("calibration.json", "settings.local.json")


def sh(*args: str) -> str:
    try:
        r = subprocess.run(args, cwd=str(ROOT), capture_output=True,
                           text=True, timeout=20)
        return (r.stdout or "").strip()
    except Exception:
        return ""


def read(p: Path, limit: int = 4_000_000) -> str:
    try:
        return io.open(p, encoding="utf-8", errors="replace").read()[-limit:]
    except OSError:
        return ""


def gate_lines(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if "GATE " in ln]


def live_rejection(line: str) -> str | None:
    """Why this line cannot be a measurement of his bench, or None if it can.

    DO NOT TRUST THE TAG ALONE. `role=` was added to stop a harness line
    being read as his hardware, and then the tag itself lied: it was derived
    from the capture's CLASS NAME, so `test_ui_smoke` -- which builds a real
    `CaptureThread`, never opens it, and publishes a verdict -- wrote nine
    `role=live` lines into the live log. Those lines are still on disk and
    this tool offered the newest of them as "the last measurement on
    record".

    The giveaways were inside the line both times: an 800x800 screen and
    exactly 60.0 fps the first time, `screen=noscreen fps=0.0 writes=0` the
    second. So the check is the one I failed to apply by eye -- read the
    rest of the line before believing its label.

    A real launch on his bench had a target screen (not `noscreen`) and
    delivered frames (fps > 0). It does NOT require control writes: this
    rule used to demand writes > 0, which the control-traffic discipline
    (RULES A4) has since made normal at ZERO -- every gate line on disk
    reads writes=0 -- so it rejected exactly the launches that were
    behaving. `noscreen` and fps=0.0 already catch the smoke test's lines.

    Returns the REASON, so the output can say why a line was set aside
    instead of silently preferring another.
    """
    if "role=live" not in line:
        return "it does not claim role=live"
    if "screen=noscreen" in line:
        return "screen=noscreen: no target screen existed, so no camera watched one"
    m = re.search(r"\bfps=([\d.]+)", line)
    if m and float(m.group(1)) <= 0.0:
        return "fps=0.0: no camera frame was ever delivered"
    return None


def is_credible_live(line: str) -> bool:
    return live_rejection(line) is None


# ---------------------------------------------------------------------------
# THE GATE'S OWN CRITERIA, applied to the logs it saved.
#
# This tool used to count a launch as good when its verdict read `ready`, and
# nothing else. `repeat_gate.ps1` applies a dozen more criteria, so on the
# logs on disk it printed "5 of 5 reached READY ... the only state in which
# the word 'ready' may be used" over gate.run5.log, whose self test reads
# detected=11/12 -- which the gate itself FAILS. The correct reading was 4 of
# 5, and the tool whose whole job is to stop a false readiness claim was
# handing the next session permission to make one (RULES C14: two readers of
# one format disagreeing, and the looser one was the one that mattered).
#
# So this mirrors `Get-LaunchJudgement` in repeat_gate.ps1, field BY NAME and
# with the same reason text, and reads the numeric limits OUT OF that script
# rather than keeping a second copy. `tests/test_rules.py` section H runs the
# real function and this one on the same crafted lines and fails if they ever
# disagree.
GATE_SCRIPT = ROOT / "scripts" / "repeat_gate.ps1"


def gate_limits() -> dict[str, float]:
    """HELD_OUT_MM_MAX, FPS_MIN and WRITE_BUDGET, read from the gate itself."""
    text = read(GATE_SCRIPT)
    out: dict[str, float] = {}
    for name in ("HELD_OUT_MM_MAX", "FPS_MIN", "WRITE_BUDGET"):
        m = re.search(rf"^\${name}\s*=\s*([\d.]+)", text, re.M)
        if m:
            out[name] = float(m.group(1))
    return out


def gate_field(text: str, name: str) -> str | None:
    """Mirrors Get-GateField: the first `name=` on a GATE line, by name."""
    m = re.search(rf"\bGATE\b[^\r\n]*?\b{name}=(\S+)", text)
    return m.group(1) if m else None


def _num(x: float) -> str:
    return f"{x:g}"


def judge_launch(text: str, done: bool, clean_close: bool,
                 timeout: int = 150) -> tuple[bool, list[str]]:
    """The gate's verdict on one saved launch: (passed, reasons)."""
    lim = gate_limits()
    if len(lim) != 3:
        return False, ["the gate's limits could not be read from repeat_gate.ps1"]
    held_max, fps_min, write_budget = (lim["HELD_OUT_MM_MAX"], lim["FPS_MIN"],
                                       lim["WRITE_BUDGET"])
    held = detected = fired = fps = rej = writes = None
    coupling = coupling_source = None
    verdict: str | None = "none"
    role = None
    if re.search(r"GATE\b.*\bverdict=", text):
        verdict = gate_field(text, "verdict")
        det = gate_field(text, "detected")
        m = re.match(r"^(\d+)/(\d+)$", det or "")
        if m:
            detected, fired = int(m.group(1)), int(m.group(2))
        v = gate_field(text, "held_out_mm")
        if v is not None:
            held = float(v)
        v = gate_field(text, "fps")
        if v is not None:
            fps = float(v)
        v = gate_field(text, "rejected_short")
        if v is not None:
            rej = int(v)
        v = gate_field(text, "writes")
        if v is not None:
            writes = int(v)
        coupling = gate_field(text, "coupling")
        coupling_source = gate_field(text, "coupling_source")
        if held is not None and held < 0:
            held = None
        role = gate_field(text, "role")

    why: list[str] = []
    if not done:
        why.append(f"never reached a verdict in {timeout}s")
    if role is None:
        why.append("the line does not say which process produced it")
    elif role.lower() != "live":
        why.append(f"this is a {role} launch, not his hardware")
    confirmed = (gate_field(text, "mapping") or "").lower() == "confirmed"
    if held is None and not confirmed:
        why.append("no calibration")
    elif held is not None and held > held_max:
        why.append(f"calibration {_num(held)}mm")
    if detected is None:
        why.append("no self test")
    elif detected < fired:
        why.append(f"self test {detected}/{fired}")
    if fps is None:
        why.append("frame rate not reported")
    elif fps < fps_min:
        why.append(f"fps {_num(fps)}")
    if rej is not None and fired and fired > 0 and rej > fired // 4:
        why.append(f"{rej} of {fired} pulses discarded as too short")
    if writes is None or writes < 0:
        why.append("control writes not reported")
    elif writes > write_budget:
        why.append(f"{writes} control writes (budget {int(write_budget)})")
    # Mirrors the gate's microphone-coupling criterion, reason text included.
    if coupling is None:
        why.append("microphone coupling not reported")
    elif coupling.lower() != "known":
        why.append("microphone coupling not known (the flat self-mute applies)")
    elif coupling_source is None or coupling_source.lower() == "none":
        why.append("microphone coupling source not reported")
    if (verdict or "").lower() != "ready":
        why.append(f"verdict: {verdict or ''}")
    if not clean_close:
        why.append("DID NOT CLOSE CLEANLY")
    return (not why), why


def saved_launch_facts(text: str) -> tuple[bool, bool]:
    """(reached a verdict, closed cleanly) as far as a SAVED LOG can say.

    The gate reads the first from the log and the second from stop_lab.ps1's
    output ("closed cleanly in Ns"), which is not kept. The app writes
    "shutdown complete" as the last thing closeEvent does before it leaves, and
    a force-kill never reaches it, so the log's tail is the closest thing on
    disk. It is an inference, and the report says so.
    """
    done = "=== VERDICT ===" in text
    tail = [ln for ln in text.splitlines() if ln.strip()][-5:]
    clean = any("shutdown complete" in ln for ln in tail)
    return done, clean


def main() -> int:
    out: list[str] = []
    add = out.append

    add("=" * 68)
    add(f"LASER SHOOTING APP -- status generated {datetime.now():%Y-%m-%d %H:%M}")
    add("=" * 68)

    # -- the honest readiness line ---------------------------------------
    #
    # RULES C10: thirteen stages in series at 95% each is a 51% chance of
    # an end-to-end success, so one good run means almost nothing. The word
    # "ready" is not to be used below 5 of 5 consecutive cold launches.
    # A LAUNCH WITH NO GATE LINE IS A FAILED LAUNCH, not a launch to skip.
    #
    # The project's own rule: an unreported check is a failure, not a pass
    # by omission. The first version of this counted only the logs that had
    # a GATE line and printed "3 of 4" from five log files -- quietly
    # dropping `gate.run4.log`, which reached shutdown without ever
    # producing a verdict. That is precisely the launch that should count
    # against the gate.
    #
    # It also showed how "4 of 5" came to be repeated all evening, in this
    # file, in CLAUDE.md and to him directly, without being true: run4
    # never reported, and `gate.run5.log` is timestamped 19:17 -- EIGHT
    # MINUTES BEFORE run1 -- so it belongs to a different invocation. The
    # files on disk hold three READY, one blocked, and one launch that
    # produced nothing, across runs that are not one gate.
    gate_files = sorted(ROOT.glob("gate.run*.log"))
    rows: list[tuple] = []
    for g in gate_files:
        try:
            mtime = g.stat().st_mtime
        except OSError:
            mtime = 0.0
        body = read(g)
        lines = gate_lines(body)
        done, clean = saved_launch_facts(body)
        passed, why = judge_launch(body, done, clean)
        if not lines:
            rows.append((g.name, "no-gate-line", "NO VERDICT", mtime, False,
                         why))
            continue
        ln = lines[-1]
        role = (re.search(r"role=(\S+)", ln) or [None, None])[1] \
            if "role=" in ln else None
        verd = (re.search(r"verdict=(\S+)", ln) or [None, "?"])[1]
        rows.append((g.name, role or "unknown(pre-role)", verd, mtime, passed,
                     why))

    add("")
    add("READINESS")
    if not rows:
        add("  no gate logs on record. Not ready.")
    else:
        # THE GATE'S OWN CRITERIA, not "the verdict said ready": see
        # judge_launch. A launch that read READY with 11 of 12 emulated shots
        # detected is a FAILED launch to the gate and must be one here.
        passed_n = sum(1 for r in rows if r[4])
        ready_n = sum(1 for r in rows if r[2] == "ready")
        add(f"  gate logs on disk: {passed_n} of {len(rows)} PASS the gate's "
            f"criteria ({ready_n} of {len(rows)} merely read READY)")
        for name, role, verd, mtime, ok, why in rows:
            when = datetime.fromtimestamp(mtime).strftime("%H:%M") if mtime else "?"
            add(f"    {name:<16} {when}  {'PASS' if ok else 'FAIL'}  "
                f"{verd:<10} {role}")
            if not ok:
                add(f"        {'; '.join(why)}")
        add("  (clean close is read from the log's closing 'shutdown complete'; "
            "the gate itself uses")
        add("   stop_lab's output, which is not saved -- an inference, not a "
            "measurement.)")
        # Are they even one run? Non-monotonic timestamps mean they are not.
        times = [r[3] for r in rows if r[3]]
        one_run = not (times and any(b < a for a, b in zip(times, times[1:])))
        if not one_run:
            add("  THESE ARE NOT ONE GATE RUN: the timestamps are out of")
            add("  order, so at least one log is from a different")
            add("  invocation. A score across them is not a gate result.")
        add("  NOT READY unless a SINGLE run shows 5 of 5 (RULES C10)."
            if passed_n < 5 or len(rows) < 5 or not one_run else
            "  5 of 5. This is the only state in which the word 'ready' may "
            "be used.")
    add("  never measured: of N real trigger pulls, how many become a hole")
    add("  in the right place. Only his gun can answer it.")

    # -- the most recent GATE line, in full ------------------------------
    # PREFERRING A LIVE ONE. A harness log is not a measurement of his
    # hardware, and the first version of this offered whichever log was
    # newest -- which was usually the harness, because the harness runs
    # unattended. That is the same mistake as reporting "17 seconds to
    # READY" from a harness line, automated.
    newest = None
    newest_at = -1.0
    best_live = None
    best_live_at = -1.0
    set_aside: list[str] = []
    for cand in list((ROOT / "logs").glob("*.log")):
        try:
            mt = cand.stat().st_mtime
        except OSError:
            continue
        lines = gate_lines(read(cand))
        if not lines:
            continue
        if mt > newest_at:
            newest, newest_at = cand, mt
        credible = any(is_credible_live(ln) for ln in lines)
        if credible and mt > best_live_at:
            best_live, best_live_at = cand, mt
        elif not credible and any("role=live" in ln for ln in lines):
            # It CLAIMED to be live and was set aside: say why, rather than
            # quietly preferring some other file.
            why = live_rejection([ln for ln in lines if "role=live" in ln][-1])
            set_aside.append(f"{cand.name}: claims role=live but {why}")
    if best_live is not None:
        newest, newest_at = best_live, best_live_at
    add("")
    add("LAST MEASUREMENT ON RECORD"
        + ("" if best_live is not None else
           "   (NO LIVE ONE EXISTS -- this is a harness run)"))
    for note in set_aside:
        add(f"  set aside: {note}")
    if newest is None:
        add("  none found in any *.log")
    else:
        line = gate_lines(read(newest))[-1]
        when = datetime.fromtimestamp(newest_at).strftime("%Y-%m-%d %H:%M")
        add(f"  {newest.name}  ({when})")
        # Wrapped, but never edited: the giveaways that a line came from the
        # harness were inside the line I misread -- an 800x800 screen and
        # exactly 60.0 fps.
        body = line.split("GATE ", 1)[1] if "GATE " in line else line
        for i in range(0, len(body), 64):
            add(f"    {body[i:i + 64]}")
        if "role=" not in body:
            add("    (no role= -- this line predates the tag and cannot name")
            add("     its own process. Do not quote it as his hardware.)")

    # -- what is verified, from git tags ---------------------------------
    add("")
    add("TAGGED STATES (verified by repetition, not by one good run)")
    tags = sh("git", "tag", "--sort=-creatordate")
    names = [t for t in tags.splitlines() if t.strip()][:6]
    if not names:
        add("  none")
    for t in names:
        subject = sh("git", "tag", "-l", t, "--format=%(subject)")
        add(f"  {t:<28} {subject[:36]}")

    # -- the files nothing may write -------------------------------------
    add("")
    add("HIS FILES -- no test, harness or script may write these")
    for name in OWNED:
        p = ROOT / name
        if not p.exists():
            add(f"  {name:<24} MISSING")
            continue
        size = p.stat().st_size
        when = datetime.fromtimestamp(p.stat().st_mtime).strftime("%m-%d %H:%M")
        extra = ""
        if name == "calibration.json":
            txt = read(p)
            m = re.search(r'"screen_size"\s*:\s*\[\s*(\d+)\s*,\s*(\d+)', txt)
            if m:
                extra = f"  screen {m.group(1)}x{m.group(2)}"
                if m.group(1) == "800":
                    extra += "  <-- SIMULATED. A harness overwrote it."
        add(f"  {name:<24} {size:>6}B  {when}{extra}")

    # -- the state of the restructure ------------------------------------
    add("")
    add("THE DIRECTOR MIGRATION (one run slot; see src/lsa/director.py)")
    lab = read(ROOT / "src" / "lsa" / "tools" / "camera_lab.py")
    # To the CLOSING paren of the tuple, at its own indentation -- not to
    # the first `)` in the text, which is the end of the first entry. The
    # first version reported one routine remaining where there are five,
    # which is the kind of quietly-wrong number this file exists to stop.
    owners = re.search(r"SCREEN_OWNERS = \(\n(.*?)\n    \)", lab, re.S)
    remaining = re.findall(r'"(_[a-z_]+)"', owners.group(1)) if owners else []
    routines = read(ROOT / "src" / "lsa" / "routines.py")
    moved = re.findall(r"^def (\w+)_job", routines, re.M)
    add(f"  moved onto it: {', '.join(moved) or 'none'}")
    add(f"  still on timers and flags: {', '.join(remaining) or 'none'}")
    add(f"  camera_lab.py is {len(lab.splitlines())} lines")

    # -- is anything of ours running right now ---------------------------
    add("")
    add("RIGHT NOW")
    # EXCLUDING THIS PROCESS. `status.py` is itself python, so it counted
    # itself and reported "something is running; the camera may be held" on
    # a completely idle machine -- a tool whose whole purpose is to state
    # the honest situation, reporting a false alarm about itself.
    me = os.getpid()
    procs = sh("powershell", "-NoProfile", "-Command",
               f"(Get-Process python,pythonw -ErrorAction SilentlyContinue "
               f"| Where-Object {{ $_.Id -ne {me} }} | Measure-Object).Count")
    add(f"  python/pythonw processes (excluding this one): {procs or 'unknown'}"
        + ("   (his screen and camera are free)" if procs == "0" else
           "   <-- something is running; the camera may be held"))
    dirty = sh("git", "status", "--porcelain")
    tracked = [ln for ln in dirty.splitlines()
               if ln[:2].strip() and not ln.endswith(".log")]
    add(f"  uncommitted tracked changes: {len(tracked)}")

    add("")
    add("BEFORE WRITING CODE: read RULES.md end to end, then run")
    add("  set LSA_NOPAUSE=1 && run_tests.bat   (~15s, no monitor)")
    add("  tests\\test_coldstart.py     (minutes, no monitor, finds the races)")
    add("ASK before taking his screen.")
    add("=" * 68)

    text = "\n".join(out)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
